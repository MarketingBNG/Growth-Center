/**
 * Null and unknown both resolve to 'internal' rather than throwing.
 *
 * A null source genuinely means "we made this number ourselves" — a lead count, a
 * pipeline total. An unknown one means a provider was added without a row here, and
 * showing it as internal is a better failure than a blank cell or a crash.
 */
export function sourceMeta(source: string | null | undefined): SourceMeta {
  if (!source) return SOURCES[INTERNAL_SOURCE];
  return SOURCES[source] ?? SOURCES[INTERNAL_SOURCE];
}

export const isLiveSource = (source: string | null | undefined) =>
  sourceMeta(source).tone === 'live';

export const isSeeded = (source: string | null | undefined) => source === DEMO_SOURCE;

