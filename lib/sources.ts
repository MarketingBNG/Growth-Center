// Where a number came from, as a display concept.
//
// Two axes already existed and were being confused with each other:
//   Channel — a business grouping (Meta Ads, Organic Search, Referral). Campaigns hang
//             off it, and Marketing already filters by it.
//   Source  — who WROTE the row: an integration id, 'demo' for the seeder, or nothing
//             at all for figures the app computes from its own tables.
//
// Only the Analytics page ever surfaced the second one, so on every other page there was
// no way to tell reported spend from invented spend. This module is that vocabulary.
//
// Deliberately import-free so client components can render a badge without dragging
// Prisma into the browser bundle — see tools/client-boundary.test.ts. That is also why
// the labels are duplicated here rather than read from lib/integrations/registry.ts,
// which imports the database. The ids are asserted against the registry by a test.

export type SourceTone = 'live' | 'seeded' | 'internal';

export type SourceMeta = {
  /** Short label for a badge. Kept to a word or two — these sit inside table cells. */
  label: string;
  /** Full name, for tooltips and the provenance line. */
  name: string;
  tone: SourceTone;
  hint: string;
};

/** Rows written by the seeder. Never real, and always labelled as such. */
